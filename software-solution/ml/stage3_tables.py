"""Write the stage-3 result tables as LaTeX (documentation/stage3_tables.tex).

Usage: python stage3_tables.py   (after stage3.py)
"""

import json
from pathlib import Path

ML = Path(__file__).parent
RESULTS = ML / "results" / "stage3"
OUT = ML.parents[1] / "documentation" / "stage3_tables.tex"
MODELS = ["clinical", "radiomic", "cnn3d", "resnet2d", "fmcib"]
NAMES = {"clinical": "Bază: vârstă + sex", "radiomic": "V1 trăsături + LR", "cnn3d": "V2 CNN 3D",
         "resnet2d": "V3 ResNet-18 2D", "fmcib": "V4 FMCIB (transfer)"}
DATASETS = {"stage2": "etapa 2 (119)", "full": "complet (146)"}


def load(dataset, model):
    path = RESULTS / dataset / model / "metrics.json"
    return json.loads(path.read_text()) if path.exists() else None


def test_table(label: str) -> str:
    rows = []
    for dataset, dname in DATASETS.items():
        for model in MODELS:
            r = load(dataset, model)
            if not r:
                continue
            t = r["test"][label]
            cv = (r.get("repeated_cv") or {}).get(label)
            cv_txt = f"{cv['auc_mean']:.2f} $\\pm$ {cv['auc_std']:.2f}" if cv else "--"
            rows.append(
                f"{dname} & {NAMES[model]} & {t['auc']:.2f} [{t['auc_ci95'][0]:.2f}, {t['auc_ci95'][1]:.2f}]"
                f" & {cv_txt} & {t['accuracy']:.2f} & {t['sensitivity']:.2f} & {t['specificity']:.2f}"
                f" & {t['f1']:.2f} & {t['brier']:.2f} \\\\")
        rows.append("\\midrule")
    rows = rows[:-1]
    first = next(load(d, m) for d in DATASETS for m in MODELS if load(d, m))
    n = {d: next(load(d, m) for m in MODELS if load(d, m))["test"][label] for d in DATASETS}
    return "\n".join([
        "\\begin{table}[htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{llcccccccc}", "\\toprule",
        "\\textbf{Set} & \\textbf{Model} & \\textbf{AUC test [IÎ 95\\%]} & \\textbf{AUC CV 5$\\times$5} & "
        "\\textbf{Acur.} & \\textbf{Sens.} & \\textbf{Spec.} & \\textbf{F1} & \\textbf{Brier} \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}",
        f"\\caption{{{label.upper()}: rezultate pe setul de test ({n['stage2']['patients']} pacienți "
        f"cu {n['stage2']['positives']} pozitivi pentru setul etapei 2; {n['full']['patients']} cu "
        f"{n['full']['positives']} pozitivi pentru setul complet) și AUC în validarea încrucișată "
        f"repetată (medie $\\pm$ deviație pe 25 de fold-uri)}}",
        f"\\label{{tab:s3_{label}}}", "\\end{table}", ""]) if first else ""


def params_table() -> str:
    rows = []
    for model in MODELS:
        r = load("full", model)
        if not r:
            continue
        p = r["hyperparameters"]
        if model == "cnn3d":
            txt = (f"Adam lr {p['lr']}, wd {p['weight_decay']}, {p['epochs']} epoci, batch {p['batch']}, "
                   f"dropout {p['dropout']}, ansamblu {p['ensemble_seeds']} rețele")
        else:
            txt = "; ".join(
                f"{lab.upper()}: " + ", ".join(
                    f"{k.split('__')[1].replace('n_components', 'PCA').replace('_', ' ')} = {v}"
                    for k, v in sorted(p[lab].items()))
                for lab in ("egfr", "kras"))
        thr = ", ".join(f"{lab.upper()} {r['test'][lab]['threshold']:.2f}" for lab in ("egfr", "kras"))
        rows.append(f"{NAMES[model]} & {txt} & {thr} \\\\")
    return "\n".join([
        "\\begin{table}[htbp]", "\\centering", "\\scriptsize",
        "\\begin{tabular}{lp{0.55\\textwidth}l}", "\\toprule",
        "\\textbf{Model} & \\textbf{Hiperparametri aleși (set complet)} & \\textbf{Prag Youden} \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}",
        "\\caption{Hiperparametrii aleși prin validare încrucișată internă pe setul de antrenare "
        "complet și pragurile de decizie}", "\\label{tab:s3_param}", "\\end{table}", ""])


def main() -> None:
    OUT.write_text("% generated by software-solution/ml/stage3_tables.py\n"
                   + test_table("egfr") + test_table("kras") + params_table())
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
